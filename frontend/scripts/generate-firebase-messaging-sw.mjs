/**
 * Writes public/firebase-messaging-sw.js from VITE_FIREBASE_* in backend/.env + frontend/.env.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  frontendRoot,
  loadMonorepoEnv,
  resolveEnvPath,
} from './load-monorepo-env.mjs';

const merged = loadMonorepoEnv();
const outPath = join(frontendRoot, 'public', 'firebase-messaging-sw.js');

const apiKey = resolveEnvPath('VITE_FIREBASE_API_KEY', merged);
const authDomain = resolveEnvPath('VITE_FIREBASE_AUTH_DOMAIN', merged);
const projectId = resolveEnvPath('VITE_FIREBASE_PROJECT_ID', merged);
const storageBucket = resolveEnvPath('VITE_FIREBASE_STORAGE_BUCKET', merged);
const messagingSenderId = resolveEnvPath('VITE_FIREBASE_MESSAGING_SENDER_ID', merged);
const appId = resolveEnvPath('VITE_FIREBASE_APP_ID', merged);
const measurementId = resolveEnvPath('VITE_FIREBASE_MEASUREMENT_ID', merged);

const configured =
  Boolean(apiKey && projectId && messagingSenderId && appId);

const resolvedAuthDomain =
  authDomain || (projectId ? `${projectId}.firebaseapp.com` : '');
const resolvedStorageBucket =
  storageBucket ||
  (projectId ? `${projectId}.firebasestorage.app` : '');

const contents = `/* eslint-disable no-undef */
/* AUTO-GENERATED by scripts/generate-firebase-messaging-sw.mjs — do not edit */
importScripts(
  'https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js',
);
importScripts(
  'https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js',
);

firebase.initializeApp({
  apiKey: ${JSON.stringify(apiKey)},
  authDomain: ${JSON.stringify(resolvedAuthDomain)},
  projectId: ${JSON.stringify(projectId)},
  storageBucket: ${JSON.stringify(resolvedStorageBucket)},
  messagingSenderId: ${JSON.stringify(messagingSenderId)},
  appId: ${JSON.stringify(appId)}${measurementId ? `,\n  measurementId: ${JSON.stringify(measurementId)}` : ''}
});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || 'FleetQuix';
  const body = payload.notification?.body || '';
  const link = payload.data?.link || '/';
  self.registration.showNotification(title, {
    body,
    icon: '/favicon.ico',
    data: { link },
  });
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const link = event.notification.data?.link || '/';
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((list) => {
      for (const client of list) {
        if ('focus' in client) {
          client.navigate(link);
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(link);
      }
      return undefined;
    }),
  );
});
`;

writeFileSync(outPath, contents, 'utf8');
if (!configured) {
  console.warn(
    '[firebase-messaging-sw] Set VITE_FIREBASE_* in backend/.env (see backend/.env.example)',
  );
} else {
  console.log('[firebase-messaging-sw] wrote', outPath);
}
